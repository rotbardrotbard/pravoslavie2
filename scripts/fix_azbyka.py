#!/usr/bin/env python3
"""Фикс кавычек-ёлочек в делимитерах строк azbyka.ts + фактические уточнения."""
import re

PATH = "/home/z/my-project/src/lib/content/azbyka.ts"
src = open(PATH, encoding="utf-8").read()

fixes = [
    # 1. Делимитеры строк: a: «... и q: «... -> a: "... / q: "..."
    ('a: «', 'a: "'),
    ('q: «', 'q: "'),
    # 2. Языковые правки
    ("тела. вопреки", "тела. Вопреки"),
    ("после одной пропуска", "после одного пропуска"),
    ("помощи Божию. главное", "помощи Божию. Главное"),
    ("это не маловеры, а забота", "это не маловерие, а забота"),
    # 3. Фактическая правка: рыба в посту
    ("в Благовещение и на Пасху — разрешается рыба, в праздники — немного вина.",
     "в Благовещение и Вербное воскресенье разрешается рыба, в праздники — немного вина."),
    # 4. Златоуст: только дословная часть
    ("Милостыня совершается не только деньгами, но и делами: помоги ближнему словом, услугой, участием — это тоже милостыня.",
     "Милостыня совершается не только деньгами, но и делами."),
    # 5. Феофан: епитимия
    ("Жизнь наша на земле есть епитимья: сетовать", "Жизнь наша на земле есть епитимия: сетовать"),
    # 6. Лествичник: номер слова не подтверждён источником
    ('source: "«Лествица», Слово 25",', 'source: "«Лествица»",'),
    ('text: "Вера — крыло молитвы: не имея этого крыла, молитва моя возвратится в недро моё.",\n    source: "«Лествица», Слово 28",',
     'text: "Вера — крыло молитвы: не имея этого крыла, молитва моя возвратится в недро моё.",\n    source: "«Лествица»",'),
    # 7. Фраза про детей в храме
    ("Наказания за «нельзя стоять» скорее оттолкнут, чем воспитают.",
     "Ругань за то, что ребёнок не может долго стоять, скорее оттолкнёт, чем воспитает."),
]

report = []
for old, new in fixes:
    n = src.count(old)
    if n:
        src = src.replace(old, new)
    report.append((n, old[:55]))

open(PATH, "w", encoding="utf-8").write(src)

for n, o in report:
    print(f"{n}x  {o}")

# контрольные подсчёты
quotes = len(re.findall(r'author: "', src))
qa = len(re.findall(r'q: "', src))
lives = len(re.findall(r'id: "', src))
print(f"\nИТОГО: цитат={quotes}, вопросов-ответов (QA_LIBRARY={qa - 12} + faq=12)={qa}, житий={lives}")
# остатки сломанных делимитеров
bad = re.findall(r'(?:a|q): «', src)
print("сломанных делимитеров осталось:", len(bad))
