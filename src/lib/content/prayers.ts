/* Молитву «Царю Небесный» не читают в период от Пасхи до Пятидесятницы. */
function withoutSpiritPrayerInPaschalPeriod(rule: Prayer, date = new Date()): Prayer {
  const pascha = orthodoxPaschaDate(date.getFullYear());
  if (!pascha) return rule;
  const day = new Date(date.getFullYear(), date.getMonth(), date.getDate(), 12);
  const pentecost = new Date(pascha.getTime() + 49 * 86_400_000);
  if (day.getTime() < pascha.getTime() || day.getTime() > pentecost.getTime()) return rule;
  return {
    ...rule,
    items: rule.items.filter((item) => item !== prayersLibrary.tsaryuNebesny.items[0]),
  };
}

export function morningRuleForDate(date = new Date()): Prayer {
  return withoutSpiritPrayerInPaschalPeriod(morningRule, date);
}

export function eveningRuleForDate(date = new Date()): Prayer {
  return withoutSpiritPrayerInPaschalPeriod(eveningRule, date);
}

