/* Расстояние по формуле гаверсинуса (км) */
export function haversineKm(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) * Math.cos((lat2 * Math.PI) / 180) * Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

export function fmtDistance(km: number): string {
  if (km < 1) return `${Math.round(km * 1000)} м`;
  return `${km.toFixed(1).replace(".", ",")} км`;
}

/* Ссылка на маршрут (Яндекс.Карты) */
export function routeUrl(lat: number, lng: number, userLat?: number, userLng?: number): string {
  const to = `${lat},${lng}`;
  return userLat !== undefined && userLng !== undefined
    ? `https://yandex.ru/maps/?rtext=${userLat},${userLng}~${to}&rtt=auto`
    : `https://yandex.ru/maps/?text=${to}`;
}
